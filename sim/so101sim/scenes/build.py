"""A scene file -> a MuJoCo model, built in memory.

The arm's own model (sim/model/so101_follower.xml, generated by tools/build_model.py) is the
starting point when the scene has an arm; everything else is added through MuJoCo's MjSpec. Nothing
is written to disk, so a scene can be loaded, changed and loaded again while the program runs.

Scene frame: z up, the surface's top at z = 0, x and y wherever the file's outline puts them.
The file and everything returned here are ground truth: for the world and the referee only.
"""
from __future__ import annotations

import math
from dataclasses import dataclass, field

import mujoco
import numpy as np

from .. import JOINTS
from ..config import MODEL_DIR
from ..rover_model import add_rover
from . import geometry as G
from .schema import COLOURS

ARM_PARKED = (0.0467, -0.6928, 0.1269, 1.6581, -1.5708, 0.9)    # an arm's starting joint angles unless the scene says otherwise:
#                                                              # teleop's home, tip 16 cm up and 20 cm ahead, fingers down, jaws open
ARM_BASE_Z = 0.0024                                      # the base's origin above its lowest face (DECISIONS M4)
FLOOR_Z = -0.75
SOLREF, SOLIMP = [0.004, 1.0], [0.95, 0.99, 0.001, 0.5, 2.0]      # stiff contacts (DECISIONS M6)
CONTACT = {"solref": SOLREF, "solimp": SOLIMP}
BOX, CYL, CAPSULE, PLANE = (mujoco.mjtGeom.mjGEOM_BOX, mujoco.mjtGeom.mjGEOM_CYLINDER,
                            mujoco.mjtGeom.mjGEOM_CAPSULE, mujoco.mjtGeom.mjGEOM_PLANE)
CAMERA_FOVY_DEG = 57.608                                 # Camera Module 3 Wide, 1080p mode, as an ideal pinhole
GRASP_FRICTION = [0.4, 0.005, 0.0001]
FIXTURE_FRICTION = [0.5, 0.005, 0.0001]


def rgba(colour, default="grey") -> list[float]:
    c = COLOURS[colour] if isinstance(colour, str) else (colour if colour is not None else COLOURS[default])
    return [float(c[0]), float(c[1]), float(c[2]), 1.0]


def yaw_quat(deg: float) -> list[float]:
    a = math.radians(deg) / 2
    return [math.cos(a), 0.0, 0.0, math.sin(a)]


def look_quat(pos, look_at, up=(0, 0, 1)) -> list[float]:
    """Orientation of a camera at pos looking at look_at (MuJoCo cameras look along their -z, +y up)."""
    pos, look_at, up = (np.asarray(v, float) for v in (pos, look_at, up))
    z = pos - look_at
    z /= np.linalg.norm(z)
    x = np.cross(up, z)
    if np.linalg.norm(x) < 1e-6:
        x = np.cross([1.0, 0, 0], z)
    x /= np.linalg.norm(x)
    y = np.cross(z, x)
    q = np.zeros(4)
    mujoco.mju_mat2Quat(q, np.column_stack([x, y, z]).flatten())
    return [float(v) for v in q]


@dataclass
class Region:
    """A box-shaped place things can be in: fixed in the scene, or riding on a body (a drawer)."""
    name: str
    lo: np.ndarray
    hi: np.ndarray
    body: str | None = None            # None: scene frame

    def holds(self, model, data, point) -> bool:
        p = np.asarray(point, float)
        if self.body is not None:
            b = model.body(self.body).id
            p = data.xmat[b].reshape(3, 3).T @ (p - data.xpos[b])
        return bool(np.all(p >= self.lo - 1e-9) and np.all(p <= self.hi + 1e-9))

    @property
    def inner_size(self) -> np.ndarray:
        return self.hi - self.lo


@dataclass
class Built:
    scene: dict
    spec: mujoco.MjSpec
    model: mujoco.MjModel
    outline: list
    rects: list
    objects: list[str] = field(default_factory=list)                 # loose bodies
    fixtures: dict[str, dict] = field(default_factory=dict)          # name -> {kind, body, top_z, joint?}
    regions: dict[str, Region] = field(default_factory=dict)
    devices: list[dict] = field(default_factory=list)                # {kind, name, ...truth about where it is}
    cameras: dict[str, dict] = field(default_factory=dict)           # camera name in the model -> {device, mounted_on}
    start: dict = field(default_factory=dict)                        # joint name -> starting position

    def new_data(self) -> mujoco.MjData:
        """Data with everything at its starting position."""
        m, d = self.model, mujoco.MjData(self.model)
        for joint, value in self.start.items():
            d.qpos[m.joint(joint).qposadr[0]] = value
        for joint, value in self.start.items():                      # position actuators hold where they start
            for a in range(m.nu):
                if m.actuator_trnid[a, 0] == m.joint(joint).id and m.actuator_trntype[a] == mujoco.mjtTrn.mjTRN_JOINT:
                    d.ctrl[a] = value
        mujoco.mj_forward(m, d)
        return d

    def device(self, kind: str) -> dict | None:
        return next((d for d in self.devices if d["kind"] == kind), None)


class SceneError(ValueError):
    """The scene cannot be built. str() is one sentence saying why."""


def _geom(body, **kw):
    return body.add_geom(**{**CONTACT, **kw})


def _fixture(spec, f: dict, built: Built):
    name, kind = f["name"], f["kind"]
    at = list(f["at_m"]) + [0.0] * (3 - len(f["at_m"]))
    body = spec.worldbody.add_body(name=name, pos=at, quat=yaw_quat(f.get("yaw_deg", 0.0)))
    col = rgba(f.get("colour"), "grey")
    info = {"kind": kind, "body": name, "top_z": at[2]}

    def box(n, pos, half, colour=None, parent=body, **kw):
        return _geom(parent, name=f"{name}_{n}", type=BOX, pos=list(pos), size=list(half), rgba=colour or col,
                     friction=kw.pop("friction", FIXTURE_FRICTION), **kw)

    def region(suffix, lo, hi, on_body=name):
        rname = name + (f"_{suffix}" if suffix else "")
        built.regions[rname] = Region(rname, np.array(lo, float), np.array(hi, float), on_body)

    if kind == "box":
        sx, sy, sz = f["size_m"]
        box("box", (0, 0, sz / 2), (sx / 2, sy / 2, sz / 2))
        info["top_z"] = at[2] + sz
        region("top", (-sx / 2, -sy / 2, sz), (sx / 2, sy / 2, sz + 0.12))
    elif kind == "bin":
        ix, iy = f["inner_m"][:2]
        t, h = f.get("wall_m", 0.003), f["wall_height_m"]
        box("n", (0, iy / 2 + t / 2, h / 2), (ix / 2 + t, t / 2, h / 2))
        box("s", (0, -iy / 2 - t / 2, h / 2), (ix / 2 + t, t / 2, h / 2))
        box("e", (ix / 2 + t / 2, 0, h / 2), (t / 2, iy / 2, h / 2))
        box("w", (-ix / 2 - t / 2, 0, h / 2), (t / 2, iy / 2, h / 2))
        info["top_z"] = at[2] + h
        region("", (-ix / 2, -iy / 2, 0.0), (ix / 2, iy / 2, h + 0.06))
    elif kind == "socket":
        ox, oy, h = f["size_m"]
        s = f["hole_m"]
        if s >= min(ox, oy):
            raise SceneError(f"fixtures '{name}': the hole ({s} m) is not smaller than the block")
        wy, wx = (oy / 2 - s / 2) / 2, (ox / 2 - s / 2) / 2
        box("n", (0, s / 2 + wy, h / 2), (ox / 2, wy, h / 2))
        box("s", (0, -s / 2 - wy, h / 2), (ox / 2, wy, h / 2))
        box("e", (s / 2 + wx, 0, h / 2), (wx, s / 2, h / 2))
        box("w", (-s / 2 - wx, 0, h / 2), (wx, s / 2, h / 2))
        info["top_z"] = at[2] + h
        region("", (-s / 2, -s / 2, 0.0), (s / 2, s / 2, h + 0.08))
    elif kind == "cabinet":
        # A roof on two side walls and a back wall, open toward its own -x, with a drawer that slides out that way.
        D, W, H = f["inner_m"]
        t = f.get("wall_m", 0.004)
        box("roof", (0, 0, H + t / 2), (D / 2, W / 2 + t, t / 2))
        box("left", (0, W / 2 + t / 2, H / 2), (D / 2, t / 2, H / 2))
        box("right", (0, -W / 2 - t / 2, H / 2), (D / 2, t / 2, H / 2))
        box("back", (D / 2 - t / 2, 0, H / 2), (t / 2, W / 2 + t, H / 2))
        info["top_z"] = at[2] + H + t
        region("top", (-D / 2, -W / 2 - t, H + t), (D / 2, W / 2 + t, H + t + 0.12))
        travel = f.get("drawer_travel_m", 0.085)
        drawer = body.add_body(name=f"{name}_drawer")
        j = drawer.add_joint(name=f"{name}_drawer", type=mujoco.mjtJoint.mjJNT_SLIDE, axis=[-1, 0, 0], range=[0, travel],
                             damping=3.0, frictionloss=0.5, armature=0.01)
        j.limited = mujoco.mjtLimited.mjLIMITED_TRUE
        cream = rgba("cream")
        x1, x0 = D / 2 - t - 0.003, -D / 2 - 0.009                  # the tray's back and front ends
        hw = W / 2 - 0.003                                           # its half width
        mid, hl = (x0 + x1) / 2, (x1 - x0) / 2
        box("drawer_floor", (mid, 0, 0.0025), (hl, hw, 0.0015), cream, drawer, mass=0.010)        # 1 mm clear of the surface
        box("drawer_left", (mid, hw - 0.0015, 0.010), (hl, 0.0015, 0.006), cream, drawer, mass=0.003)
        box("drawer_right", (mid, -hw + 0.0015, 0.010), (hl, 0.0015, 0.006), cream, drawer, mass=0.003)
        box("drawer_back", (x1 - 0.0015, 0, 0.010), (0.0015, hw, 0.006), cream, drawer, mass=0.003)
        fh = (H - 0.012) / 2
        box("drawer_front", (x0, 0, 0.001 + fh), (0.004, W / 2 - 0.001, fh), cream, drawer, mass=0.010)
        box("drawer_handle", (x0 - 0.002, 0, 0.001 + 2 * fh + 0.015), (0.006, 0.006, 0.015), rgba("black"), drawer,
            mass=0.004, friction=[1.0, 0.02, 0.0005], condim=4)
        info["joint"] = f"{name}_drawer"
        built.start[f"{name}_drawer"] = float(f.get("drawer_open_m", 0.0))
        region("drawer", (x0 + 0.006, -hw + 0.003, 0.004), (x1 - 0.003, hw - 0.003, 0.004 + H - 0.008), f"{name}_drawer")
    elif kind == "shelf":
        sx, sy, th = f["size_m"]
        top = f["height_m"]
        if top <= th:
            raise SceneError(f"fixtures '{name}': height_m ({top}) must be more than the top's thickness ({th})")
        box("top", (0, 0, top - th / 2), (sx / 2, sy / 2, th / 2))
        if f.get("support", "legs") == "back":                       # an overhang: one wall along its +x edge
            box("back", (sx / 2 - 0.004, 0, (top - th) / 2), (0.004, sy / 2, (top - th) / 2))
        else:
            for k, (ex, ey) in enumerate(((1, 1), (1, -1), (-1, 1), (-1, -1))):
                box(f"leg{k}", (ex * (sx / 2 - 0.005), ey * (sy / 2 - 0.005), (top - th) / 2), (0.005, 0.005, (top - th) / 2))
        info["top_z"] = at[2] + top
        region("top", (-sx / 2, -sy / 2, top), (sx / 2, sy / 2, top + 0.12))
        region("under", (-sx / 2 + 0.01, -sy / 2 + 0.01, 0.0), (sx / 2 - 0.01, sy / 2 - 0.01, top - th))
    elif kind == "parts":
        top = 0.0
        for k, p in enumerate(f["parts"]):
            half = [v / 2 for v in p["box_m"]]
            kw = {"friction": [p["friction"], 0.005, 0.0001]} if "friction" in p else {}
            box(p.get("name", f"part{k}"), p["at_m"], half, rgba(p.get("colour"), "grey") if "colour" in p else None, **kw)
            top = max(top, p["at_m"][2] + half[2])
        info["top_z"] = at[2] + top
    built.fixtures[name] = info


def _object(spec, o: dict, built: Built):
    name = o["name"]
    if o["shape"] == "box":
        half = [v / 2 for v in o["size_m"]]
        height, gtype, size = o["size_m"][2], BOX, half
    else:
        r, half_len = o["size_m"][0] / 2, o["size_m"][1] / 2
        height, gtype, size = (2 * r if o.get("lying") else 2 * half_len), CYL, [r, half_len, 0]
    base = 0.0
    if "on" in o:
        if o["on"] not in built.fixtures:
            raise SceneError(f"objects '{name}': there is no fixture '{o['on']}' to stand on")
        base = built.fixtures[o["on"]]["top_z"]
        fx = next(f for f in built.scene.get("fixtures", []) if f["name"] == o["on"])
        xy = o["at_m"][:2] if "at_m" in o else fx["at_m"][:2]
    else:
        xy = o["at_m"][:2]
    if "at_m" in o and len(o["at_m"]) == 3:
        base = o["at_m"][2]                                           # the height of its underside
    quat = yaw_quat(o.get("yaw_deg", 0.0))
    if o["shape"] == "cylinder" and o.get("lying"):
        tip = np.zeros(4)
        mujoco.mju_mulQuat(tip, np.array(quat), np.array([math.sqrt(0.5), 0, math.sqrt(0.5), 0]))
        quat = [float(v) for v in tip]
    body = spec.worldbody.add_body(name=name, pos=[xy[0], xy[1], base + height / 2 + 0.0001], quat=quat)
    body.add_freejoint(name=f"{name}_free")
    fr = [o["friction"], 0.005, 0.0001] if "friction" in o else GRASP_FRICTION
    _geom(body, name=name, type=gtype, size=size, mass=o["mass_kg"], rgba=rgba(o["colour"]), friction=fr, condim=4,
          contype=3)                                                  # bit 2: what the arm's wires collide with
    built.objects.append(name)


def build(scene: dict) -> Built:
    """The scene as a compiled model, with the names and places the referee needs.

    Assumes the file's fields are well-formed (scenes.schema.check). Raises SceneError for what
    only shows when building (a thing standing on a fixture that does not exist, a model that
    does not compile).
    """
    surface = scene["surface"]
    outline = [[float(x), float(y)] for x, y in surface["outline_m"]]
    if not G.is_right_angled(outline):
        raise SceneError("surface.outline_m: only outlines with right-angled corners along x and y are supported")
    rects = G.rectangles(outline)
    if not rects or abs(sum((r[2] - r[0]) * (r[3] - r[1]) for r in rects) - G.area(outline)) > 1e-9:
        raise SceneError("surface.outline_m: the outline crosses itself")
    arm = next((d for d in scene["devices"] if d["kind"] == "arm"), None)
    if arm is not None:
        spec = mujoco.MjSpec.from_file(str(MODEL_DIR / "so101_follower.xml"))
        base = spec.body("base")
        base.pos = [arm["at_m"][0], arm["at_m"][1], ARM_BASE_Z]
        base.quat = yaw_quat(arm.get("facing_deg", 0.0))
    else:
        spec = mujoco.MjSpec()
        spec.compiler.degree = False
    spec.modelname = f"scene_{scene['name']}"
    spec.option.timestep = 0.002
    spec.option.integrator = mujoco.mjtIntegrator.mjINT_IMPLICITFAST
    spec.option.cone = mujoco.mjtCone.mjCONE_ELLIPTIC
    spec.option.impratio = 10
    g = spec.visual.global_
    g.offwidth, g.offheight, g.azimuth, g.elevation = 1920, 1080, 150, -25
    light = scene.get("light", {})
    amb = float(light.get("ambient", 0.25))
    spec.visual.headlight.ambient = [amb] * 3
    spec.visual.headlight.diffuse = [0.4, 0.4, 0.4]
    spec.visual.headlight.specular = [0, 0, 0]
    spec.visual.quality.shadowsize = 4096
    built = Built(scene=scene, spec=spec, model=None, outline=outline, rects=rects)
    wb = spec.worldbody

    cx, cy = np.mean(np.asarray(outline), axis=0)
    for which, default_from, default_strength, shadow in (("key", (cx + 0.1, cy - 0.35, 1.3), 0.65, True),
                                                          ("fill", (cx - 0.55, cy + 0.45, 1.0), 0.25, False)):
        l = light.get(which, {})
        src = np.array(l.get("from_m", default_from), float)
        aim = np.array([cx, cy, 0.0]) - src
        s = float(l.get("strength", default_strength))
        wb.add_light(name=which, pos=src.tolist(), dir=(aim / np.linalg.norm(aim)).tolist(), diffuse=[s, s, s * 0.97],
                     castshadow=shadow)

    # The surface: solid down to the floor (a thin top lets a fast object through, DECISIONS M5), with a lip.
    depth = float(surface.get("depth_m", -FLOOR_Z))
    col = rgba(surface.get("colour"), "wood")
    fr = [float(surface.get("friction", 0.5)), 0.005, 0.0001]
    wb.add_geom(name="floor", type=PLANE, pos=[cx, cy, FLOOR_Z], size=[3, 3, 0.05], rgba=[0.33, 0.33, 0.36, 1], **CONTACT)
    for k, (x0, y0, x1, y1) in enumerate(rects):
        wb.add_geom(name="table" if len(rects) == 1 else f"table_{k}", type=BOX, pos=[(x0 + x1) / 2, (y0 + y1) / 2, -depth / 2],
                    size=[(x1 - x0) / 2, (y1 - y0) / 2, depth / 2], rgba=col, friction=fr, contype=3, **CONTACT)
    lh, lt = float(surface["lip_height_m"]), float(surface.get("lip_thickness_m", 0.008))
    ccw = G.signed_area(outline) > 0
    for k, (a, b) in enumerate(G.edges(outline)):
        d = (b - a) / np.linalg.norm(b - a)
        out = np.array([d[1], -d[0]]) if ccw else np.array([-d[1], d[0]])       # away from the surface
        mid = (a + b) / 2 + out * lt / 2
        half_len = np.linalg.norm(b - a) / 2 + lt                     # run past both corners so they close
        size = [half_len, lt / 2, (lh + 0.01) / 2] if abs(d[0]) > 0.5 else [lt / 2, half_len, (lh + 0.01) / 2]
        wb.add_geom(name=f"lip_{k}", type=BOX, pos=[mid[0], mid[1], (lh - 0.01) / 2], size=size,
                    rgba=[col[0] * 0.8, col[1] * 0.8, col[2] * 0.8, 1], friction=fr, contype=3, **CONTACT)

    for f in scene.get("fixtures", []):
        _fixture(spec, f, built)
    for r in scene.get("regions", []):
        x0, y0, x1, y1 = r["rect_m"]
        z = r.get("z_m", [0.0, 0.12])
        built.regions[r["name"]] = Region(r["name"], np.array([min(x0, x1), min(y0, y1), z[0]]), np.array([max(x0, x1), max(y0, y1), z[1]]))
    for o in scene.get("objects", []):
        _object(spec, o, built)

    for d in scene["devices"]:
        kind, name = d["kind"], d["name"]
        if kind == "arm":
            built.devices.append({"kind": "arm", "name": name, "at_m": list(d["at_m"][:2]), "facing_deg": float(d.get("facing_deg", 0.0)),
                                  "base_body": "base"})
            built.cameras["wrist"] = {"device": name, "mounted_on": "gripper"}
            for j, q in zip(JOINTS, d.get("joints_rad", ARM_PARKED)):
                built.start[j] = float(q)
        elif kind == "camera":
            pos, aim = d["at_m"], d["looking_at_m"]
            q = look_quat(pos, aim)
            wb.add_camera(name=name, pos=list(pos), quat=q, fovy=CAMERA_FOVY_DEG)
            R = np.zeros(9)
            mujoco.mju_quat2Mat(R, np.array(q))
            back = np.asarray(pos, float) + R.reshape(3, 3)[:, 2] * 0.014          # the housing sits behind the lens
            house = wb.add_body(name=f"{name}_housing", pos=back.tolist(), quat=q)
            _geom(house, name=f"{name}_housing", type=BOX, size=[0.02, 0.016, 0.012], rgba=[0.2, 0.2, 0.25, 1])
            if d.get("post", True):
                foot_z = 0.0 if G.inside(outline, back[0], back[1]) else FLOOR_Z
                if back[2] - 0.02 > foot_z:
                    wb.add_geom(name=f"{name}_post", type=CAPSULE, size=[0.006, 0, 0],
                                fromto=[back[0], back[1], back[2] - 0.018, back[0], back[1], foot_z + 0.006],
                                rgba=[0.35, 0.35, 0.38, 1], **CONTACT)
            built.devices.append({"kind": "camera", "name": name, "at_m": list(pos), "looking_at_m": list(aim)})
            built.cameras[name] = {"device": name, "mounted_on": "world"}
        elif kind == "rover":
            info = add_rover(spec, name, d["at_m"][0], d["at_m"][1], math.radians(d.get("facing_deg", 0.0)), CONTACT)
            built.devices.append({"kind": "rover", "name": name, "at_m": list(d["at_m"][:2]),
                                  "facing_deg": float(d.get("facing_deg", 0.0)), **info})
    try:
        built.model = spec.compile()
    except Exception as e:                       # MuJoCo's own message names the element
        raise SceneError(f"the model does not compile: {str(e).splitlines()[0]}") from e
    return built
