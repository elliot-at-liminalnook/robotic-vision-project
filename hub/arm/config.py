"""The arm's own configuration: its shape, its servos, its limits.

Built-in knowledge (docs/MULTI_DEVICE_PLAN.md, 5.3): about the arm, the same wherever it stands.
The files are read from where the repo keeps them; nothing here is about a scene.
"""
from __future__ import annotations

import json
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
MODEL_DIR = ROOT / "sim" / "model"               # so101_follower.xml: the arm's shape (generated by sim/tools/build_model.py)
CONFIG_DIR = ROOT / "sim" / "config"             # servos.toml, safety.toml


def _load(name: str) -> dict:
    with (CONFIG_DIR / name).open("rb") as f:
        return tomllib.load(f)


def load_wrist_mount() -> dict:
    """The wrist camera mount placement (hardware/wrist_mount/wrist_mount_pose.json)."""
    return json.loads((ROOT / "hardware/wrist_mount/wrist_mount_pose.json").read_text())


def wrist_roll_range() -> tuple[float, float]:
    """Wrist roll range that keeps the side-mounted camera clear of the arm.

    Spans pi, so every top-down jaw orientation is still reachable. The
    generated model's wrist_roll joint and actuator are limited to it too.
    """
    lo, hi = load_wrist_mount()["wrist_roll_range_rad"]
    return float(lo), float(hi)


def load_servos() -> dict:
    return _load("servos.toml")


def load_safety() -> dict:
    """Limits for the command filter and the physics monitor (config/safety.toml)."""
    return _load("safety.toml")


def servo_limits(arm: str = "follower") -> dict:
    """Servo torque/speed at the configured supply voltage (DC motor: both scale with voltage).

    Returns stall_torque_nm, no_load_speed_rad_s, gripper_torque_nm (torque-limit
    register applied), rated values and the voltages.
    """
    f = load_servos()[arm]
    k = float(f["supply_voltage_v"]) / float(f["rated_voltage_v"])
    stall = float(f["torque_limit_nm"]) * k
    return dict(stall_torque_nm=stall, no_load_speed_rad_s=float(f["max_speed_rad_s"]) * k,
                gripper_torque_nm=stall * float(f["gripper_torque_limit_frac"]),
                rated_stall_torque_nm=float(f["torque_limit_nm"]), rated_speed_rad_s=float(f["max_speed_rad_s"]),
                supply_voltage_v=float(f["supply_voltage_v"]), rated_voltage_v=float(f["rated_voltage_v"]),
                voltage_scale=k)


def position_loop(arm: str = "follower") -> dict:
    """Servo position-loop model + command compensation settings, with derived stiffness.

    Adds stiffness_nm_per_rad (stall torque / sat_error) and back_emf_nm_s_per_rad
    (stall torque / no-load speed), both at the supply voltage.
    """
    import math
    cfg = dict(load_servos()[arm]["position_loop"])
    lim = servo_limits(arm)
    cfg["sat_error_rad"] = math.radians(float(cfg["sat_error_deg"]))
    cfg["stiffness_nm_per_rad"] = lim["stall_torque_nm"] / cfg["sat_error_rad"]
    cfg["back_emf_nm_s_per_rad"] = lim["stall_torque_nm"] / lim["no_load_speed_rad_s"]
    return cfg

